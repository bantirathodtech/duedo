-- EXECUDO: Behavior Archetypes (10 Execution Modes)
CREATE TABLE IF NOT EXISTS public.execudo_behaviors (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    title TEXT NOT NULL,
    archetype TEXT NOT NULL CHECK (
        archetype IN (
            'medicine',
            'timetable',
            'habit',
            'scheduled',
            'adhoc',
            'sequential',
            'conditional',
            'collaborative',
            'progressive',
            'multi_anchor'
        )
    ),
    config JSONB NOT NULL DEFAULT '{}'::jsonb,
    streak_count INT NOT NULL DEFAULT 0,
    best_streak INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS idx_execudo_behaviors_user ON public.execudo_behaviors(user_id);
CREATE INDEX IF NOT EXISTS idx_execudo_behaviors_archetype ON public.execudo_behaviors(user_id, archetype);
ALTER TABLE public.execudo_behaviors ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can manage own behaviors" ON public.execudo_behaviors FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
-- EXECUDO: Behavior Execution Audit Trail
CREATE TABLE IF NOT EXISTS public.execudo_executions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    behavior_id UUID NOT NULL REFERENCES public.execudo_behaviors(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    status TEXT NOT NULL CHECK (
        status IN ('completed', 'skipped', 'failed', 'verified')
    ),
    proof_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    notes TEXT,
    executed_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS idx_execudo_executions_user ON public.execudo_executions(user_id, executed_at);
CREATE INDEX IF NOT EXISTS idx_execudo_executions_behavior ON public.execudo_executions(behavior_id, executed_at);
ALTER TABLE public.execudo_executions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can manage own executions" ON public.execudo_executions FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
-- EXECUDO: Collaborative Circles & Caretaker Mode
CREATE TABLE IF NOT EXISTS public.execudo_circles (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    creator_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    name TEXT NOT NULL,
    invite_code TEXT UNIQUE NOT NULL DEFAULT substring(
        md5(random()::text)
        from 1 for 8
    ),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
ALTER TABLE public.execudo_circles ENABLE ROW LEVEL SECURITY;
CREATE TABLE IF NOT EXISTS public.execudo_circle_members (
    circle_id UUID NOT NULL REFERENCES public.execudo_circles(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'member' CHECK (
        role IN ('admin', 'witness', 'caretaker', 'member')
    ),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    PRIMARY KEY (circle_id, user_id)
);
ALTER TABLE public.execudo_circle_members ENABLE ROW LEVEL SECURITY;
-- Circle RLS: Members can view the circle
CREATE POLICY "Circle members can view circles" ON public.execudo_circles FOR
SELECT USING (
        auth.uid() = creator_id
        OR EXISTS (
            SELECT 1
            FROM public.execudo_circle_members m
            WHERE m.circle_id = id
                AND m.user_id = auth.uid()
        )
    );
CREATE POLICY "Creator can manage circle" ON public.execudo_circles FOR ALL USING (auth.uid() = creator_id) WITH CHECK (auth.uid() = creator_id);
CREATE POLICY "Members can view circle membership" ON public.execudo_circle_members FOR
SELECT USING (
        user_id = auth.uid()
        OR EXISTS (
            SELECT 1
            FROM public.execudo_circle_members m
            WHERE m.circle_id = circle_id
                AND m.user_id = auth.uid()
        )
    );
CREATE POLICY "Users can join or admins can manage circle members" ON public.execudo_circle_members FOR ALL USING (
    user_id = auth.uid()
    OR EXISTS (
        SELECT 1
        FROM public.execudo_circles c
        WHERE c.id = circle_id
            AND c.creator_id = auth.uid()
    )
);