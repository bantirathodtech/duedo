-- DUEDO: User Financial Settings
CREATE TABLE IF NOT EXISTS public.user_settings (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    monthly_income NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    currency TEXT NOT NULL DEFAULT 'INR',
    notifications_enabled BOOLEAN NOT NULL DEFAULT true,
    reminder_days_before INT NOT NULL DEFAULT 1,
    payday_of_month INT NOT NULL DEFAULT 1,
    projection_months INT NOT NULL DEFAULT 12,
    theme_mode TEXT NOT NULL DEFAULT 'system',
    payment_streak INT NOT NULL DEFAULT 0,
    is_savage_mode BOOLEAN NOT NULL DEFAULT false,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
ALTER TABLE public.user_settings ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can manage own settings" ON public.user_settings FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
-- DUEDO: Obligations (Liabilities, EMIs, Bills, Recurring)
CREATE TABLE IF NOT EXISTS public.obligations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    title TEXT NOT NULL,
    type INT NOT NULL DEFAULT 0,
    -- 0: EMI, 1: One-time, 2: Recurring Bill
    amount NUMERIC(12, 2) NOT NULL,
    start_date TIMESTAMPTZ NOT NULL,
    end_date TIMESTAMPTZ,
    emi_duration_months INT,
    grace_period_days INT NOT NULL DEFAULT 0,
    emi_paid_months INT NOT NULL DEFAULT 0,
    priority INT NOT NULL DEFAULT 0,
    status INT NOT NULL DEFAULT 0,
    -- 0: Pending, 1: Paid, 2: Overdue
    category TEXT,
    notes TEXT,
    next_due_date TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT true,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS idx_obligations_user ON public.obligations(user_id);
CREATE INDEX IF NOT EXISTS idx_obligations_status ON public.obligations(user_id, status);
CREATE INDEX IF NOT EXISTS idx_obligations_due ON public.obligations(user_id, next_due_date);
ALTER TABLE public.obligations ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can manage own obligations" ON public.obligations FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
-- DUEDO: Payments Ledger
CREATE TABLE IF NOT EXISTS public.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    obligation_id BIGINT NOT NULL REFERENCES public.obligations(id) ON DELETE CASCADE,
    amount_paid NUMERIC(12, 2) NOT NULL,
    payment_type TEXT,
    note TEXT,
    paid_date TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
CREATE INDEX IF NOT EXISTS idx_payments_user_obs ON public.payments(user_id, obligation_id);
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can manage own payments" ON public.payments FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
